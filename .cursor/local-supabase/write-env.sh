#!/usr/bin/env bash
# Create server/.env and client/.env for local development if they don't exist.
#
# Values point the API at the local Supabase-compatible stack. Because dotenv does
# not override variables already present in the process environment, real Supabase
# credentials supplied as Cloud Agent secrets (SUPABASE_URL, SUPABASE_SERVICE_KEY,
# JWT_SECRET) take precedence over these local defaults automatically.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/../.." && pwd)"

SUPABASE_PORT="${LOCAL_SUPABASE_PORT:-3002}"
SERVICE_KEY="$(node "$HERE/mint-service-key.js")"

if [ ! -f "$REPO_ROOT/server/.env" ]; then
  echo "[env] writing server/.env (local dev defaults)"
  cat > "$REPO_ROOT/server/.env" <<EOF
# Local development defaults — generated by .cursor/local-supabase/write-env.sh
# Points at the local Supabase-compatible stack (PostgREST + proxy over Postgres).
# To use a real Supabase project instead, set SUPABASE_URL / SUPABASE_SERVICE_KEY /
# JWT_SECRET as Cloud Agent secrets; those override these values at runtime.
SUPABASE_URL=http://127.0.0.1:${SUPABASE_PORT}
SUPABASE_SERVICE_KEY=${SERVICE_KEY}
JWT_SECRET=local-dev-jwt-secret-change-me
PORT=3000
# Forms sync needs Google credentials; disabled by default for local dev.
DISABLE_FORMS_SYNC_CRON=1
EOF
else
  echo "[env] server/.env already exists; leaving as-is"
fi

if [ ! -f "$REPO_ROOT/client/.env" ]; then
  echo "[env] writing client/.env (local dev defaults)"
  cat > "$REPO_ROOT/client/.env" <<EOF
# Local development defaults — generated by .cursor/local-supabase/write-env.sh
VITE_API_URL=http://localhost:3000
EOF
else
  echo "[env] client/.env already exists; leaving as-is"
fi
